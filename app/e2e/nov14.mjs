// 14 Nov 2026: no Show completed on the home page; All / Pro / Perso written side by side; the cart
// grey like the other icons; Upcoming lists every day for two months at least, up to the last
// planned task; bigger stars on the phone. TEST Vikunja only. Usage: node e2e/nov14.mjs <app> <api> <user> <pass>
import { chromium } from 'playwright-core';
const [base, api, user, pass] = process.argv.slice(2);
const jwt = (await (await fetch(api + '/api/v1/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: user, password: pass }) })).json()).token;
const H = { Authorization: 'Bearer ' + jwt, 'Content-Type': 'application/json' };
const req = async (m, p, b) => { for (let k = 0; k < 6; k++) { const r = await fetch(api + p, { method: m, headers: H, body: b ? JSON.stringify(b) : undefined }).catch(() => null); if (r && (r.ok || r.status < 500)) return r.json().catch(() => null); await new Promise((x) => setTimeout(x, 400 * (k + 1))); } return null; };
let ok = 0, n = 0;
const check = (name, cond, got = '') => { n++; if (cond) ok++; console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}${cond ? '' : '  → ' + String(got).slice(0, 300)}`); };
const st = Date.now().toString(36).slice(-4);
const P = await req('PUT', '/api/v1/projects', { title: `Nov14 ${st}` });
const labels = await req('GET', '/api/v1/labels?per_page=500');
const valid = labels.find((l) => l.title === 'ctx:validated') ?? (await req('PUT', '/api/v1/labels', { title: 'ctx:validated' }));
const far = new Date(); far.setDate(far.getDate() + 90); far.setHours(9, 0, 0, 0);
const T = await req('PUT', `/api/v1/projects/${P.id}/tasks`, { title: `far away ${st}`, start_date: far.toISOString() });
await req('PUT', `/api/v1/tasks/${T.id}/labels`, { label_id: valid.id });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const init = ([a, j]) => { if (sessionStorage.getItem('s')) return; sessionStorage.setItem('s', '1'); localStorage.setItem('vikunja_api_url', a); localStorage.setItem('vikunja_jwt', j); localStorage.setItem('news_seen', '2099'); localStorage.setItem('view', 'all'); };
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript(init, [api, jwt]);
const p = await ctx.newPage();
await p.goto(base + '/'); await p.waitForTimeout(6000);
check('home: no Show completed', (await p.getByText(/show completed/i).count()) === 0);
const views = p.locator('.views').getByRole('radio');
check('top bar: All, Pro, Perso written side by side, no "View"', (await views.allInnerTexts()).map((x) => x.trim()).join() === 'All,Pro,Perso' && (await p.locator('header, .topbar').first().getByText('View', { exact: true }).count()) === 0);
await p.getByRole('radio', { name: 'Pro', exact: true }).click(); await p.waitForTimeout(800);
check('top bar: a click switches to Pro', (await p.getByRole('radio', { name: 'Pro', exact: true }).getAttribute('aria-checked')) === 'true');
await p.getByRole('radio', { name: 'All', exact: true }).click(); await p.waitForTimeout(500);
check('menu: the Shopping icon is a grey line icon, no emoji', (await p.locator('a.place', { hasText: 'Shopping' }).locator('svg').count()) === 1 && !(await p.locator('a.place', { hasText: 'Shopping' }).innerText()).includes('🛒'));
await p.keyboard.press('n'); await p.waitForTimeout(800);
const cart = p.locator('button.cart').first();
const col = await cart.evaluate((e) => getComputedStyle(e).color);
check('new task box: the cart is a grey icon (no emoji)', (await cart.locator('svg').count()) === 1 && (() => { const c = col.match(/\d+/g).slice(0, 3).map(Number); return Math.max(...c) - Math.min(...c) < 24; })(), col);
await p.keyboard.press('Escape'); await p.waitForTimeout(400);
check('menu: Tomorrow', (await p.locator('a.place', { hasText: 'Tomorrow' }).count()) === 1);
await p.goto(base + '/upcoming'); await p.waitForTimeout(3000);
const nDays = await p.locator('section.day').count();
check('upcoming: every day listed, at least two months', nDays >= 61, nDays);
check('upcoming: up to the task planned in three months', (await p.getByText(`far away ${st}`).count()) === 1 && nDays >= 91, nDays);
check('upcoming: month names between the days', (await p.locator('h2.month').count()) >= 2, await p.locator('h2.month').count());
check('upcoming: no week or month blocks any more', (await p.locator('.later').count()) === 0);
await p.goto(base + '/today-review'); await p.waitForTimeout(2500);
check('Tomorrow: the page title is Tomorrow', (await p.locator('h1').first().innerText()).trim() === 'Tomorrow' && (await p.title()).startsWith('Tomorrow —'));
await ctx.close();
const ph = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await ph.addInitScript(init, [api, jwt]);
const q = await ph.newPage();
await q.goto(base + '/today-review'); await q.waitForTimeout(6000);
const star = q.locator('.choose').first();
const box = await star.boundingBox();
check('phone: the moons are easy to hit (40 px)', box && box.width >= 40 && box.height >= 40, JSON.stringify(box));
await q.goto(base + '/'); await q.waitForTimeout(2500);
const over = await q.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
check('phone: the top bar fits (no sideways scrolling)', over <= 1, over);
await browser.close();
await req('DELETE', `/api/v1/tasks/${T.id}`);
await req('DELETE', `/api/v1/projects/${P.id}`);
console.log(`${ok}/${n} passed`);
process.exit(ok === n ? 0 : 1);
