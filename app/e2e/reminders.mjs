// Reminders (19 Nov 2026): set on a task's page, kept on the server, kept when the task is changed
// afterwards, and removed with ×. TEST Vikunja only. Usage: node e2e/reminders.mjs <app> <api> <user> <pass>
import { chromium } from 'playwright-core';
const [base, api, user, pass] = process.argv.slice(2);
const jwt = (await (await fetch(api + '/api/v1/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: user, password: pass }) })).json()).token;
const H = { Authorization: 'Bearer ' + jwt, 'Content-Type': 'application/json' };
const req = async (m, p, b) => { for (let k = 0; k < 6; k++) { const r = await fetch(api + p, { method: m, headers: H, body: b ? JSON.stringify(b) : undefined }).catch(() => null); if (r && (r.ok || r.status < 500)) return r.json().catch(() => null); await new Promise((x) => setTimeout(x, 400 * (k + 1))); } return null; };
let ok = 0, n = 0;
const check = (name, cond, got = '') => { n++; if (cond) ok++; console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}${cond ? '' : '  → ' + String(got).slice(0, 300)}`); };
const st = Date.now().toString(36).slice(-4);
const P = await req('PUT', '/api/v1/projects', { title: `Remind ${st}` });
const T = await req('PUT', `/api/v1/projects/${P.id}/tasks`, { title: `call the bank ${st}` });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, timezoneId: 'Europe/Paris' });
await ctx.addInitScript(([a, j]) => { if (sessionStorage.getItem('s')) return; sessionStorage.setItem('s', '1'); localStorage.setItem('vikunja_api_url', a); localStorage.setItem('vikunja_jwt', j); localStorage.setItem('news_seen', '2099'); }, [api, jwt]);
const p = await ctx.newPage();
await p.goto(base + '/'); await p.waitForTimeout(6000);
await p.goto(base + `/task/${T.id}`); await p.waitForTimeout(2500);
const field = p.locator('.field', { has: p.locator('.label', { hasText: 'Remind' }) });
check('task page: a Remind line', (await field.count()) === 1);
await field.locator('input[type="date"]').fill('2026-12-03'); await field.locator('input[type="date"]').press('Tab');
await field.locator('input[type="time"]').fill('10:15'); await field.locator('input[type="time"]').press('Tab');
await p.waitForTimeout(3500);
let s = await req('GET', `/api/v1/tasks/${T.id}`);
const at = (s.reminders ?? [])[0]?.reminder;
check('the reminder is on the server, at 10:15 Paris time on 3 Dec', at && new Date(at).toISOString() === '2026-12-03T09:15:00.000Z', JSON.stringify(s.reminders));
await p.locator('.title-input, h1 textarea, textarea.title, input.title').first().fill(`call the bank today ${st}`).catch(() => {});
await p.keyboard.press('Enter').catch(() => {});
await p.waitForTimeout(500);
await p.goto(base + `/task/${T.id}`); await p.waitForTimeout(1500);
const due = p.locator('.field', { has: p.locator('.label', { hasText: 'Due' }) });
await due.locator('input[type="date"]').fill('2026-12-05'); await due.locator('input[type="date"]').press('Tab');
await p.waitForTimeout(3500);
s = await req('GET', `/api/v1/tasks/${T.id}`);
check('changing the task afterwards keeps the reminder', (s.reminders ?? []).length === 1 && s.due_date?.startsWith('2026-12-05'), JSON.stringify({ r: s.reminders, d: s.due_date }));
await p.reload(); await p.waitForTimeout(3000);
check('shown again after a reload', (await field.locator('input[type="time"]').inputValue()) === '10:15', await field.locator('input[type="time"]').inputValue());
await field.getByRole('button', { name: 'Remove the reminder' }).click(); await p.waitForTimeout(3500);
s = await req('GET', `/api/v1/tasks/${T.id}`);
check('× removes it', !(s.reminders ?? []).length, JSON.stringify(s.reminders));
await browser.close();
await req('DELETE', `/api/v1/tasks/${T.id}`); await req('DELETE', `/api/v1/projects/${P.id}`);
console.log(`${ok}/${n} passed`);
process.exit(ok === n ? 0 : 1);
